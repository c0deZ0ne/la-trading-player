# export JDK_PATH=/usr/lib/jvm/java-17-openjdk-amd64					# you can use openjdk 11, too
# export JAVA_HOME=$JDK_PATH
# export PATH=$JAVA_HOME/bin:$PATH

# # =====================================================

# QT_PATH_RUNTIME=$QT_BASE_PATH/$QT_VERSION/$ANDROID_ARCH
